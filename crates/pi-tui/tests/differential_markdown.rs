fn normalize_for_lexer(source: &str) -> String {
    source.replace('\t', "   ")
}

#[test]
fn lex_matches_marked_token_stream() {
    let mut oracle = TsOracle::spawn("markdown-oracle.ts", SOURCE_DIRECTORY);
    let mut cases: Vec<Value> = Vec::new();
    for (index, markdown) in LEX_CORPUS.iter().enumerate() {
        cases.push(json!({ "name": format!("case-{index}"), "markdown": markdown }));
    }
    for (index, markdown) in SPEC_CORPUS.iter().enumerate() {
        cases.push(json!({ "name": format!("spec-{index}"), "markdown": markdown }));
    }
    let response = oracle.request(&json!({
        "id": 1,
        "operation": "markdown_lex",
        "cases": cases,
    }));
    assert_eq!(response["ok"], Value::Bool(true), "{response}");

    let results = response["output"]["results"].as_array().expect("results array");
    let corpus: Vec<&str> = LEX_CORPUS.iter().chain(SPEC_CORPUS.iter()).copied().collect();
    assert_eq!(results.len(), corpus.len());

    for (index, result) in results.iter().enumerate() {
        let normalized = normalize_for_lexer(corpus[index]);
        let mut tokens = lexer::lex(&normalized);
        trim_partial_closing_fences(&mut tokens);
        let actual = serde_json::to_value(&tokens).expect("tokens serialize");
        assert_eq!(
            actual, result["tokens"],
            "token mismatch for case {index}: {:?}",
            corpus[index]
        );
    }
}

fn render_cases() -> Vec<Value> {
    let mut cases = Vec::new();
    for (index, markdown) in LEX_CORPUS.iter().enumerate() {
        for width in [20usize, 40, 80] {
            cases.push(json!({
                "name": format!("render-{index}-{width}"),
                "markdown": markdown,
                "width": width,
                "paddingX": 0,
                "paddingY": 0,
                "hyperlinks": false,
            }));
        }
    }
    for (index, markdown) in SPEC_CORPUS.iter().enumerate() {
        for width in [25usize, 60] {
            cases.push(json!({
                "name": format!("spec-render-{index}-{width}"),
                "markdown": markdown,
                "width": width,
                "paddingX": 0,
                "paddingY": 0,
                "hyperlinks": false,
            }));
        }
    }
    for (index, markdown) in LEX_CORPUS.iter().enumerate().step_by(7) {
        cases.push(json!({
            "name": format!("render-hyperlinks-{index}"),
            "markdown": markdown,
            "width": 60,
            "paddingX": 0,
            "paddingY": 0,
            "hyperlinks": true,
        }));
        cases.push(json!({
            "name": format!("render-padding-{index}"),
            "markdown": markdown,
            "width": 50,
            "paddingX": 2,
            "paddingY": 1,
            "hyperlinks": false,
        }));
    }
    let options_cases: &[(&str, Value)] = &[
        (
            "1. alpha\n1. beta\n1. gamma",
            json!({ "preserveOrderedListMarkers": true }),
        ),
        (
            "  4. forth\n  3. third\n\n10) ten\n7) seven\n\n+ plus\n* star\n- minus\n+",
            json!({ "preserveOrderedListMarkers": true }),
        ),
        (
            "\\*escaped\\* and \\`code\\`",
            json!({ "preserveBackslashEscapes": true }),
        ),
        ("$x$ and $$\ny = 2\n$$", json!({ "renderLatex": false })),
        ("$x$ and $$\ny = 2\n$$", json!({})),
    ];
    for (index, (markdown, options)) in options_cases.iter().enumerate() {
        cases.push(json!({
            "name": format!("options-{index}"),
            "markdown": markdown,
            "width": 40,
            "paddingX": 0,
            "paddingY": 0,
            "hyperlinks": false,
            "options": options,
        }));
    }

    let style_cases: &[(&str, Value)] = &[
        ("alpha `code` beta", json!({ "color": "gray", "italic": true })),
        ("**bold** and `code`", json!({ "color": "gray", "italic": true })),
        ("# heading", json!({ "color": "gray", "bold": true })),
        ("plain", json!({ "bgColor": "bgBlue" })),
        ("- a\n- b", json!({ "bgColor": "bgBlue", "color": "gray" })),
        ("line\nline", json!({ "bgColor": "bgBlue", "underline": true })),
    ];
    for (index, (markdown, style)) in style_cases.iter().enumerate() {
        cases.push(json!({
            "name": format!("style-{index}"),
            "markdown": markdown,
            "width": 30,
            "paddingX": 1,
            "paddingY": 1,
            "hyperlinks": false,
            "defaultTextStyle": style,
        }));
    }
    cases
}

#[test]
fn render_matches_typescript_markdown_component() {
    let cases = render_cases();
    let mut oracle = TsOracle::spawn("markdown-oracle.ts", SOURCE_DIRECTORY);
    let response = oracle.request(&json!({
        "id": 2,
        "operation": "markdown_render",
        "cases": cases,
    }));
    assert_eq!(response["ok"], Value::Bool(true), "{response}");
    let results = response["output"]["results"].as_array().expect("results array");
    assert_eq!(results.len(), cases.len());

    for (index, result) in results.iter().enumerate() {
        let case = &cases[index];
        let hyperlinks = case["hyperlinks"].as_bool().unwrap_or(false);
        set_capabilities(TerminalCapabilities {
            images: None,
            true_color: false,
            hyperlinks,
        });
        let options_json = &case["options"];
        let options = MarkdownOptions {
            preserve_ordered_list_markers: options_json["preserveOrderedListMarkers"].as_bool().unwrap_or(false),
            preserve_backslash_escapes: options_json["preserveBackslashEscapes"].as_bool().unwrap_or(false),
        };
        let style_json = &case["defaultTextStyle"];
        let default_style = (!style_json.is_null()).then(|| DefaultTextStyle {
            color: style_json["color"]
                .as_str()
                .map(|_| Box::new(|text: &str| apply_chalk(&[GRAY], text)) as Box<dyn Fn(&str) -> String>),
            bg_color: style_json["bgColor"]
                .as_str()
                .map(|_| Box::new(|text: &str| apply_chalk(&[BG_BLUE], text)) as Box<dyn Fn(&str) -> String>),
            bold: style_json["bold"].as_bool().unwrap_or(false),
            italic: style_json["italic"].as_bool().unwrap_or(false),
            strikethrough: style_json["strikethrough"].as_bool().unwrap_or(false),
            underline: style_json["underline"].as_bool().unwrap_or(false),
        });
        let mut markdown = Markdown::new(
            case["markdown"].as_str().unwrap_or(""),
            case["paddingX"].as_u64().unwrap_or(0) as usize,
            case["paddingY"].as_u64().unwrap_or(0) as usize,
            Box::new(ChalkTheme),
            default_style,
            options,
        );
        let width = case["width"].as_u64().unwrap_or(80) as usize;
        let actual = markdown.render(width);
        reset_capabilities_cache();
        let expected: Vec<String> = result["lines"]
            .as_array()
            .expect("lines array")
            .iter()
            .map(|line| line.as_str().unwrap_or("").to_string())
            .collect();
        assert_eq!(
            actual, expected,
            "render mismatch for {}: {:?} width {width}",
            case["name"], case["markdown"]
        );
    }
}
