#[test]
fn keys_match_the_pinned_typescript_source() {
    let mut oracle = oracle::TsOracle::spawn("tui-leaves-oracle.ts", SOURCE_DIRECTORY);

    let parse_request: Vec<Value> = PARSE_CASES
        .iter()
        .map(|(data, kitty)| json!({ "data": data, "kitty": kitty }))
        .collect();
    let response = oracle.request(&json!({
        "id": "keys-parse",
        "operation": "keys_parse",
        "cases": parse_request,
    }));
    assert_eq!(response["ok"], true, "oracle failed: {response}");
    let results = response["output"]["results"].as_array().unwrap();
    for ((data, kitty), expected) in PARSE_CASES.iter().zip(results) {
        set_kitty_protocol_active(*kitty);
        let actual = parse_key(data);
        set_kitty_protocol_active(false);
        assert_eq!(
            actual.as_deref(),
            expected.as_str(),
            "parse mismatch for {data:?} kitty={kitty}"
        );
    }

    let match_request: Vec<Value> = MATCH_CASES
        .iter()
        .map(|(data, key_id, kitty)| json!({ "data": data, "keyId": key_id, "kitty": kitty }))
        .collect();
    let response = oracle.request(&json!({
        "id": "keys-match",
        "operation": "keys_match",
        "cases": match_request,
    }));
    assert_eq!(response["ok"], true, "oracle failed: {response}");
    let results = response["output"]["results"].as_array().unwrap();
    for ((data, key_id, kitty), expected) in MATCH_CASES.iter().zip(results) {
        set_kitty_protocol_active(*kitty);
        let actual = matches_key(data, key_id);
        set_kitty_protocol_active(false);
        assert_eq!(
            actual,
            expected.as_bool().unwrap(),
            "match mismatch for {data:?} / {key_id:?} kitty={kitty}"
        );
    }

    let response = oracle.request(&json!({
        "id": "keys-decode",
        "operation": "keys_decode",
        "cases": DECODE_CASES,
    }));
    assert_eq!(response["ok"], true, "oracle failed: {response}");
    let results = response["output"]["results"].as_array().unwrap();
    for (data, expected) in DECODE_CASES.iter().zip(results) {
        assert_eq!(
            decode_kitty_printable(data).as_deref(),
            expected["kitty"].as_str(),
            "kitty decode mismatch for {data:?}"
        );
        assert_eq!(
            decode_printable_key(data).as_deref(),
            expected["printable"].as_str(),
            "printable decode mismatch for {data:?}"
        );
        assert_eq!(
            is_key_release(data),
            expected["release"].as_bool().unwrap(),
            "release mismatch for {data:?}"
        );
        assert_eq!(
            is_key_repeat(data),
            expected["repeat"].as_bool().unwrap(),
            "repeat mismatch for {data:?}"
        );
    }
}
