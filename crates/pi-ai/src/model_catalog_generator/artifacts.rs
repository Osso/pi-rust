use super::*;
use std::{
    fs,
    io::{self, Write},
    path::Path,
};

/// The three filesystem operations performed by the frozen generator.
pub trait CatalogFileSystem {
    fn read_dir(&mut self, path: &Path) -> Result<Vec<JsString>, GeneratorError>;
    fn remove(&mut self, path: &Path) -> Result<(), GeneratorError>;
    fn write(&mut self, path: &Path, content: &str) -> Result<(), GeneratorError>;
}
pub struct NativeCatalogFileSystem;
fn io_error(error: io::Error, syscall: &str, path: &Path) -> GeneratorError {
    let path = pi_js_compat::node_fs::decode_node_path(path.as_os_str());
    NativeNodeError::from(pi_js_compat::node_fs::node_fs_error_record(&error, syscall, &path)).into()
}
impl CatalogFileSystem for NativeCatalogFileSystem {
    fn read_dir(&mut self, path: &Path) -> Result<Vec<JsString>, GeneratorError> {
        let entries = fs::read_dir(path).map_err(|error| io_error(error, "scandir", path))?;
        let mut names = entries
            .map(|entry| entry.map(|entry| entry.file_name()))
            .collect::<Result<Vec<_>, _>>()
            .map_err(|error| io_error(error, "scandir", path))?;
        names.sort();
        Ok(names
            .iter()
            .map(|name| pi_js_compat::node_fs::decode_node_path(name))
            .collect())
    }
    fn remove(&mut self, path: &Path) -> Result<(), GeneratorError> {
        let metadata = fs::symlink_metadata(path).map_err(|error| io_error(error, "lstat", path))?;
        if metadata.is_dir() {
            let path = pi_js_compat::node_fs::decode_node_path(path.as_os_str());
            let info = object([
                ("code", text("EISDIR")),
                ("message", text("is a directory")),
                ("path", JsValue::String(path.clone())),
                ("syscall", text("rm")),
                ("errno", JsValue::Number(21.0)),
            ]);
            return Err(NativeNodeError::from_constructor(
                pi_js_compat::node_error::NativeErrorClass::SystemError,
                pi_js_compat::js_format!("Path is a directory: rm returned EISDIR (is a directory) {}", path),
            )
            .with_property("code", text("ERR_FS_EISDIR"))
            .with_property("info", info)
            .with_property("errno", JsValue::Number(21.0))
            .with_property("syscall", text("rm"))
            .with_property("path", JsValue::String(path))
            .into());
        }
        fs::remove_file(path).map_err(|error| io_error(error, "unlink", path))
    }
    fn write(&mut self, path: &Path, content: &str) -> Result<(), GeneratorError> {
        let mut file = fs::OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(true)
            .open(path)
            .map_err(|error| io_error(error, "open", path))?;
        file.write_all(content.as_bytes())
            .map_err(|error| NativeNodeError::from(pi_js_compat::node_fs::node_file_write_error_record(&error)).into())
    }
}
fn include_source(ids: &[JsString]) -> Result<String, GeneratorError> {
    let mut output =
        String::from("// Generated by generate-models; do not edit.\nconst PROVIDER_CATALOGS: &[(&str, &str)] = &[\n");
    for id in ids {
        let id = id.to_utf8().map_err(|error| named_error("Error", error.to_string()))?;
        let path = format!("../../data/providers/{id}.json");
        output.push_str(&format!("    ({id:?}, include_str!({path:?})),\n"));
    }
    output.push_str("];\n");
    Ok(output)
}
fn materialize_provider(models: &JsValue) -> Result<JsValue, GeneratorError> {
    let mut sorted = entries(models);
    sorted.sort_by(|(left, _), (right, _)| left.cmp(right));
    let mut output = indexmap::IndexMap::new();
    for (_, model) in sorted {
        let emitted = emission::materialize(model)?;
        let id = emitted["id"].as_string().expect("materialized string ID").clone();
        // Two distinct source IDs may become the same evaluated literal key.
        output.insert(id, emitted);
    }
    Ok(JsValue::Object(output))
}
impl Generator<'_> {
    pub fn generate(&mut self, root: &Path) -> Result<JsValue, GeneratorError> {
        self.generate_with_filesystem(root, &mut NativeCatalogFileSystem)
    }
    pub fn generate_with_filesystem(
        &mut self,
        root: &Path,
        filesystem: &mut dyn CatalogFileSystem,
    ) -> Result<JsValue, GeneratorError> {
        let catalog = self.generate_catalog()?;
        let providers = root.join("crates/pi-ai/data/providers");
        // No staging, manifest or rollback: a failure leaves the source's partial writes.
        for name in filesystem.read_dir(&providers)? {
            if name.units().ends_with(JsString::from(".json").units()) {
                let path = providers.join(pi_js_compat::js_json::encode_node_utf8(&name));
                filesystem.remove(&path)?;
            }
        }
        for (provider, models) in entries(&catalog) {
            let materialized = materialize_provider(models)?;
            let filename = pi_js_compat::js_json::encode_node_utf8(provider) + ".json";
            filesystem.write(
                &providers.join(filename),
                &(pi_js_compat::js_json::stringify_lossless(&materialized) + "\n"),
            )?;
        }
        self.log(
            "log",
            &format!(
                "Generated {} catalogs under crates/pi-ai/data/providers/",
                entries(&catalog).len()
            ),
        );
        let ids = entries(&catalog)
            .into_iter()
            .map(|(id, _)| id.clone())
            .collect::<Vec<_>>();
        filesystem.write(
            &root.join("crates/pi-ai/src/providers/model_catalogs_generated.rs"),
            &include_source(&ids)?,
        )?;
        self.log(
            "log",
            "Generated crates/pi-ai/src/providers/model_catalogs_generated.rs",
        );
        self.log("log", "\nModel Statistics:");
        self.log("log", &format!("  Total tool-capable models: {}", self.total_models));
        self.log("log", &format!("  Reasoning-capable models: {}", self.reasoning_models));
        for (provider, count) in self.provider_counts.clone() {
            let message = pi_js_compat::js_format!("  {}: {} models", provider, count);
            self.emit(ConsoleLog {
                is_error: false,
                args: vec![JsValue::String(message).into()],
            });
        }
        Ok(catalog)
    }
}
