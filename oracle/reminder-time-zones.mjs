// Generate or verify the reminder timezone table from the host tzdata and Node ICU.
// The Node version records generation provenance; ICU and tzdata versions determine the reference inputs.
import { readFileSync } from 'node:fs';

const source = readFileSync('/usr/share/zoneinfo/tzdata.zi', 'utf8');
const version = source.match(/^# version (\S+)/)?.[1];
if (!version) throw new Error('tzdata version missing');
const ids = new Set(['UTC']);
for (const line of source.split('\n')) {
    const fields = line.split(/\s+/);
    if (fields[0] === 'Z') ids.add(fields[1]);
    if (fields[0] === 'L') ids.add(fields[2]);
}
const entries = [...ids].sort().flatMap(id => {
    try {
        return [[id, new Intl.DateTimeFormat('en-US', {timeZone: id}).resolvedOptions().timeZone]];
    } catch (error) {
        if (error instanceof RangeError) return [];
        throw error;
    }
});
if (process.argv[2] === '--json') {
    console.log(JSON.stringify({node: process.versions.node, icu: process.versions.icu, tz: process.versions.tz, tzdata: version, entries}));
} else {
    console.log(`// Generated by oracle/reminder-time-zones.mjs; Node ${process.versions.node}, ICU ${process.versions.icu}, Node tz ${process.versions.tz}, system tzdata ${version}.`);
    console.log('pub(super) const NODE_TIME_ZONES: &[(&str, &str)] = &[');
    for (const [id, canonical] of entries) console.log(`    (${JSON.stringify(id)}, ${JSON.stringify(canonical)}),`);
    console.log('];');
}
